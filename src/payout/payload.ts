/**
 * The bytes two of a vault's four payout signers sign for a fast payout:
 * `PACK(("fast-payout:v1", chain_id, vault, session_id, amount))`, a 5-tuple
 * right comb.
 *
 * The leaf encodings are the ones Michelson's `PACK` serialises, prefixed
 * with the `0x05` PACK magic: `07 07` for a `Pair`, `01 <u32 BE len> <utf8>`
 * for a string, `0a <u32 BE len> <bytes>` for bytes, `00 <zarith>` for the
 * `mutez` amount (the same bytes a `nat` gets). The chain id is its 4 raw
 * bytes, the vault its 22-byte forged address `01 ‖ hash20 ‖ 00`, and the
 * session id its 16 raw bytes, never the hyphenated text.
 *
 * One rule, several implementations: the vault contract's own `sp.pack`, the
 * sequencer's and validator's Rust encoder, and this port are all pinned to
 * the same fixture (`fast-payout-vectors.json`, generated by an independent
 * pytezos script), so a signature the vault accepted verifies here over the
 * identical bytes.
 */
import { decodeChainId, decodeKt1 } from '../wire/signature';

/** Domain-separation tag `fast_payout` verifies under. */
export const FAST_PAYOUT_DOMAIN = 'fast-payout:v1';

/** The vault's `PAYOUT_SIGNER_COUNT`: four fast-payout signers. */
export const PAYOUT_SIGNER_COUNT = 4;

/** The vault's `PAYOUT_THRESHOLD`: two of the four must sign. */
export const PAYOUT_THRESHOLD = 2;

/** The `0x05` byte Tezos `PACK` prefixes every packed value with. */
const PACK_MAGIC = 0x05;

const TAG_INT = 0x00;
const TAG_STRING = 0x01;
const TAG_PRIM_2 = 0x07;
const TAG_BYTES = 0x0a;
const PRIM_PAIR = 0x07;

function u32be(n: number): number[] {
    return [(n >>> 24) & 0xff, (n >>> 16) & 0xff, (n >>> 8) & 0xff, n & 0xff];
}

/**
 * Michelson's signed zarith of a non-negative integer: the first byte carries
 * the sign at `0x40` and six value bits, every later byte seven, little-endian
 * by group, with `0x80` as the continuation flag.
 */
export function zarithNat(value: bigint): number[] {
    if (value < 0n) {
        throw new RangeError('a mutez amount is never negative');
    }

    const out: number[] = [];
    let rest = value;
    let byte = Number(rest & 0x3fn);

    rest >>= 6n;

    if (rest > 0n) {
        byte |= 0x80;
    }

    out.push(byte);

    while (rest > 0n) {
        let next = Number(rest & 0x7fn);

        rest >>= 7n;

        if (rest > 0n) {
            next |= 0x80;
        }

        out.push(next);
    }

    return out;
}

function packString(text: string): number[] {
    const utf8 = new TextEncoder().encode(text);

    return [TAG_STRING, ...u32be(utf8.length), ...utf8];
}

function packBytes(bytes: Uint8Array | number[]): number[] {
    return [TAG_BYTES, ...u32be(bytes.length), ...bytes];
}

function packPair(first: number[], second: number[]): number[] {
    return [TAG_PRIM_2, PRIM_PAIR, ...first, ...second];
}

/** The forged `address` bytes `PACK` emits for an originated contract: `01 ‖ hash20 ‖ 00`. */
export function forgedVaultAddress(vault: string): Uint8Array {
    const hash = decodeKt1(vault);
    const out = new Uint8Array(22);

    out[0] = 0x01;
    out.set(hash, 1);
    out[21] = 0x00;

    return out;
}

/**
 * The payload for a fast payout of `amountMutez` to the session `sessionId`
 * (its 16 raw bytes) on `vault` (`KT1…`), on the chain `chainId` (`NetX…`).
 */
export function fastPayoutPayload(
    chainId: string,
    vault: string,
    sessionId: Uint8Array,
    amountMutez: bigint,
): Uint8Array {
    if (sessionId.length !== 16) {
        throw new RangeError(`a session id is 16 bytes, found ${sessionId.length}`);
    }

    const packed = packPair(
        packString(FAST_PAYOUT_DOMAIN),
        packPair(
            packBytes(decodeChainId(chainId)),
            packPair(
                packBytes(forgedVaultAddress(vault)),
                packPair(packBytes(sessionId), [TAG_INT, ...zarithNat(amountMutez)]),
            ),
        ),
    );

    return new Uint8Array([PACK_MAGIC, ...packed]);
}
